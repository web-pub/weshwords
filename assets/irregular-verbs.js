/** Dictionnaire base → [base, prét, pp, fr] */
export const IRR_BY_BASE = Object.fromEntries(IRREGULAR_VERBS.map(v => [v[0], v]));

/**
 * Cherche un verbe irrégulier dans une expression anglaise
 * ex. « to keep in touch » → keep ; « to be good at » → be ; « I'm lucky » → null
 */
export function findIrregular(en, nature = "") {
  const words = String(en || "").toLowerCase().replace(/[’']/g, " ").split(/[^a-z]+/).filter(Boolean);
  if (!words.length) return null;
  // « to + verbe » (ex. to keep in touch)
  if (words[0] === "to" && IRR_BY_BASE[words[1]]) return IRR_BY_BASE[words[1]];
  // sinon seulement si le mot est indiqué comme verbe (évite « light blue », « a cut »…)
  if (/verbe/i.test(nature) && IRR_BY_BASE[words[0]]) return IRR_BY_BASE[words[0]];
  return null;
}
